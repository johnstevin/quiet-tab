// Copies the Inter variable webfont out of node_modules into public/fonts so it
// ships inside the extension.
//
// Why vendor it at all? A new tab must render instantly and work offline. A
// remote font would mean a network round-trip on every tab (visible FOUT) and
// would break with no connection. Local + `font-display: block` gives us a
// sub-10ms disk read and zero metric swap.
//
// Runs automatically on `postinstall` and again inside `npm run build`.

import { copyFile, mkdir, readdir, stat, writeFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const PKG_DIR = join(ROOT, 'node_modules', '@fontsource-variable', 'inter')
const OUT_DIR = join(ROOT, 'public', 'fonts')

// The latin-only weight axis subset. Verified upstream size: 48,256 bytes.
const FONT_FILE = 'inter-latin-wght-normal.woff2'
const EXPECTED_BYTES = 48256

async function main() {
  if (!existsSync(PKG_DIR)) {
    console.warn(
      '[sync-font] @fontsource-variable/inter not installed yet — skipping.\n' +
        '            This is expected before the first `npm install`.',
    )
    return
  }

  await mkdir(OUT_DIR, { recursive: true })

  const src = join(PKG_DIR, 'files', FONT_FILE)
  if (!existsSync(src)) {
    const available = existsSync(join(PKG_DIR, 'files'))
      ? (await readdir(join(PKG_DIR, 'files'))).filter((f) => f.endsWith('.woff2')).join('\n  - ')
      : '(no files/ directory)'
    throw new Error(
      `[sync-font] expected font not found:\n  ${src}\n\nAvailable woff2 files:\n  - ${available}`,
    )
  }

  const dest = join(OUT_DIR, FONT_FILE)
  await copyFile(src, dest)

  const { size } = await stat(dest)
  const flag = size === EXPECTED_BYTES ? 'OK' : `WARN (expected ${EXPECTED_BYTES})`
  console.log(`[sync-font] ${FONT_FILE} -> public/fonts/  ${size} bytes  [${flag}]`)

  // Carry the licence along with the binary. OFL-1.1 requires the copyright
  // notice and licence to travel with any redistributed copy of the font.
  const licenceSrc = ['LICENSE', 'LICENSE.md', 'LICENSE.txt']
    .map((n) => join(PKG_DIR, n))
    .find((p) => existsSync(p))

  const licenceDest = join(OUT_DIR, 'Inter-OFL-LICENSE.txt')
  if (licenceSrc) {
    await copyFile(licenceSrc, licenceDest)
    console.log('[sync-font] Inter-OFL-LICENSE.txt -> public/fonts/  [OK]')
  } else {
    await writeFile(
      licenceDest,
      [
        'Inter is licensed under the SIL Open Font License 1.1.',
        'Copyright (c) 2016-present The Inter Project Authors',
        'https://github.com/rsms/inter',
        '',
        'Full licence text: https://openfontlicense.org/open-font-license-official-text/',
        '',
        '(Upstream package shipped no LICENSE file; this stub was generated by',
        ' scripts/sync-font.mjs to satisfy the OFL attribution requirement.)',
      ].join('\n'),
      'utf8',
    )
    console.warn('[sync-font] no upstream LICENSE found — wrote attribution stub.')
  }
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err)
  process.exitCode = 1
})
